# -----------------------------------------
# LLM Reasoning (FLAN-T5 — better than GPT2)
# -----------------------------------------

print("\nLoading LLM model (first time takes ~30s)...")

generator = pipeline(
    "text2text-generation",
    model="google/flan-t5-base",
    device=0 if torch.cuda.is_available() else -1
)

prompt = "Solve step by step: A pen costs 10, sells 15, sold 20. What is the profit?"

llm_output = generator(prompt, max_new_tokens=80)

print("\nLLM Generated Answer:\n")
print(llm_output[0]["generated_text"])