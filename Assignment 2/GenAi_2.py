import pandas as pd
import torch
from transformers import pipeline
from IPython.display import display

# -----------------------------------------
# Problem
# -----------------------------------------
problem = """
A shopkeeper buys a pen for ₹10 and sells it for ₹15.
He sells 20 pens. What is the profit?
"""

print("\nPROBLEM:\n", problem)


# -----------------------------------------
# Prompting Techniques (Manual reasoning)
# -----------------------------------------

def zero_shot(problem):
    return "Profit per pen = 15 - 10 = 5. Total profit = 5 × 20 = ₹100"


def few_shot(problem):
    examples = """
Example 1:
CP = 20, SP = 30, Quantity = 10
Profit = (30-20)*10 = 100

Example 2:
CP = 50, SP = 70, Quantity = 5
Profit = (70-50)*5 = 100
"""
    answer = "Using pattern: (15-10)*20 = ₹100"
    return examples + "\nAnswer:\n" + answer


def chain_of_thought(problem):
    return """
Step 1: Cost Price = 10
Step 2: Selling Price = 15
Step 3: Profit per pen = 5
Step 4: Total profit = 5 × 20 = ₹100
Final Answer: ₹100
"""


def interview_prompting(problem):
    return """
Q1: Cost price per pen? → 10
Q2: Selling price per pen? → 15
Q3: Profit per pen? → 5
Q4: Profit for 20 pens? → ₹100
"""


def tree_of_thought(problem):
    return """
Approach 1: (15-10) × 20 = 100

Approach 2:
Revenue = 15×20 = 300
Cost = 10×20 = 200
Profit = 300-200 = 100

Conclusion → ₹100
"""


# -----------------------------------------
# Print outputs
# -----------------------------------------

methods_output = {
    "Zero-shot": zero_shot(problem),
    "Few-shot": few_shot(problem),
    "Chain of Thought": chain_of_thought(problem),
    "Interview": interview_prompting(problem),
    "Tree of Thoughts": tree_of_thought(problem),
}

for name, output in methods_output.items():
    print(f"\n{name} Output:\n{output}")


